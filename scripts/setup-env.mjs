#!/usr/bin/env node
/**
 * setup-env.mjs
 *
 * Creates the local environment files for the POC:
 *   1. <repo>/.env             – copied from .env.example with generated JWT secrets
 *   2. <repo>/apps/web/.env.local – NEXT_PUBLIC_API_URL for Next.js (it does not read the root .env)
 *
 * Refuses to overwrite existing files unless --force is passed.
 *
 *   pnpm setup:env
 *   pnpm setup:env --force
 */
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const force = process.argv.includes("--force");

const examplePath = join(repoRoot, ".env.example");
const envPath = join(repoRoot, ".env");
const webEnvPath = join(repoRoot, "apps", "web", ".env.local");

const log = (msg) => console.log(`[setup-env] ${msg}`);
const fail = (msg) => {
  console.error(`[setup-env] ERROR: ${msg}`);
  process.exit(1);
};

if (!existsSync(examplePath)) fail(`.env.example not found at ${examplePath}`);

const secret = () => randomBytes(32).toString("hex"); // 64 hex chars, well above the 32-char minimum

// ── 1. root .env ─────────────────────────────────────────────
if (existsSync(envPath) && !force) {
  log(`.env already exists – leaving it untouched (use --force to overwrite)`);
} else {
  let content = readFileSync(examplePath, "utf8");
  const setVar = (name, value) => {
    const re = new RegExp(`^${name}=.*$`, "m");
    if (!re.test(content)) fail(`${name} not found in .env.example`);
    content = content.replace(re, `${name}=${value}`);
  };
  setVar("JWT_SECRET", secret());
  setVar("JWT_REFRESH_SECRET", secret());
  writeFileSync(envPath, content, "utf8");
  log(`wrote ${envPath} (JWT secrets generated)`);
}

// ── 2. apps/web/.env.local ───────────────────────────────────
const apiUrlMatch = readFileSync(envPath, "utf8").match(/^NEXT_PUBLIC_API_URL=(.*)$/m);
const apiUrl = (apiUrlMatch?.[1] ?? "http://localhost:4000/api/v1").trim();

if (existsSync(webEnvPath) && !force) {
  log(`apps/web/.env.local already exists – leaving it untouched (use --force to overwrite)`);
} else {
  mkdirSync(dirname(webEnvPath), { recursive: true });
  writeFileSync(
    webEnvPath,
    [
      "# Generated by scripts/setup-env.mjs – Next.js reads this file, not the monorepo-root .env",
      `NEXT_PUBLIC_API_URL=${apiUrl}`,
      "",
    ].join("\n"),
    "utf8",
  );
  log(`wrote ${webEnvPath}`);
}

log("done. Next: pnpm db:up && pnpm db:migrate && pnpm db:seed && pnpm dev");
